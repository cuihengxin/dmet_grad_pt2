from pyscf.lib import logger
from pyscf import lib
import numpy as np
from numpy import einsum
from functools import reduce
from functools import partial
einsum = partial(einsum, optimize=True)

def solve_amplitude(t1_, koopmans, overlap, overlap_discard, V1, Delta, ic_coeff, s_thres):
    if overlap_discard.shape[-1] == 0:
        return np.zeros_like(koopmans), np.zeros_like(overlap), np.zeros_like(V1), np.zeros_like(Delta)
    
    ic_coeff_ = einsum('...P,Pm->...m', t1_, overlap_discard)
    overlap_discard_ = einsum('...P,...m->Pm', t1_, ic_coeff)

    SKS = reduce(lib.dot, (overlap_discard.T, koopmans, overlap_discard))
    SKS = np.tril(SKS) + np.tril(SKS, k=-1).T
    A = SKS + Delta[...,None,None] * np.eye(overlap_discard.shape[-1])
    B_ = np.linalg.solve(A.swapaxes(-1,-2), ic_coeff_[...,None])[...,0]

    A_ = -einsum('...m,...n->...mn', B_, ic_coeff)
    Delta_ = einsum('...mm->...', A_)
    SKS_ = A_.reshape(-1, A_.shape[-2], A_.shape[-1]).sum(axis=0)
    SKS_ = np.tril(SKS_) + np.tril(SKS_.T, k=-1)

    V1_ = einsum('...m,Pm->...P', B_, overlap_discard)
    overlap_discard_ += einsum('...P,...m->Pm', V1, B_)

    koopmans_ = reduce(lib.dot, (overlap_discard, SKS_, overlap_discard.T))
    overlap_discard_ += reduce(lib.dot, (koopmans, overlap_discard, SKS_.T))
    overlap_discard_ += reduce(lib.dot, (koopmans.T, overlap_discard, SKS_))

    S_eval, S_evec = np.linalg.eigh(overlap)
    S_ind_nonzero = np.where(S_eval > s_thres)[0]
    S_eval_, S_evec_ = np.zeros_like(S_eval), np.zeros_like(S_evec)
    S_eval_discard = S_eval[S_ind_nonzero]
    S_evec_discard = S_evec[:, S_ind_nonzero]
    S_eval_[S_ind_nonzero] = -0.5 * S_eval_discard**(-1.5) * einsum('ri,ri->i', S_evec_discard, overlap_discard_)
    S_evec_[:, S_ind_nonzero] = overlap_discard_ / np.sqrt(S_eval_discard)[None, :]

    rotated = lib.dot(S_evec.T, S_evec_)
    gap = S_eval[None, :] - S_eval[:, None]
    gap_inv = np.zeros_like(gap)
    scale = max(float(np.max(np.abs(S_eval), initial=0.0)), 1.0)
    mask = (~np.eye(S_eval.size, dtype=bool)) & (np.abs(gap) > 100.0 * np.finfo(float).eps * scale)
    gap_inv[mask] = 1/gap[mask]
    overlap_ = reduce(lib.dot, (S_evec, np.diag(S_eval_) + gap_inv * rotated, S_evec.T))
    overlap_ = 0.5 * (overlap_ + overlap_.T)
    overlap_ = 2.0 * np.tril(overlap_, k=-1) + np.diag(np.diagonal(overlap_))
    return koopmans_, overlap_, V1_, Delta_

def compute_t1_0(nevpt_grad):
    nevpt = nevpt_grad.nevpt
    cput0 = (logger.process_clock(), logger.perf_counter())
    nevpt.log.debug("\nComputing T[0]^(1) gradients...")

    e_core = nevpt.mo_energy.c
    e_extern = nevpt.mo_energy.e
    V1 = nevpt._V1["0"]
    t1 = nevpt._t1["0"]
    t1_ = nevpt_grad._t1["0"]

    Delta = e_extern[None, None, None, :] + e_extern[None, None, :, None] - e_core[None, :, None, None] - e_core[:, None, None, None]
    V1_ = t1_ / Delta
    Delta_ = -t1_ * V1 / Delta**2
    nevpt_grad.v2e.cece[:] -= einsum('IJAB->IAJB', V1_)
    nevpt_grad.v2e.cece[:] += 2 * einsum('ijab->iajb', t1)
    nevpt_grad.v2e.cece[:] -= einsum('ijab->jaib', t1)
    nevpt_grad.mo_energy.e += Delta_.sum(axis=(0,1,2))
    nevpt_grad.mo_energy.e += Delta_.sum(axis=(0,1,3))
    nevpt_grad.mo_energy.c -= Delta_.sum(axis=(0,2,3))
    nevpt_grad.mo_energy.c -= Delta_.sum(axis=(1,2,3))

    nevpt.log.timer("computing T[0]^(1) gradients", *cput0)
    return

def compute_t1_p1(nevpt_grad):
    nevpt = nevpt_grad.nevpt
    cput0 = (logger.process_clock(), logger.perf_counter())
    nevpt.log.debug("\nComputing T[+1]^(1) gradients...")

    e_core = nevpt.mo_energy.c
    e_extern = nevpt.mo_energy.e
    v_cace = nevpt.v2e.cace
    v_aaaa = nevpt.v2e.aaaa
    h1eff = nevpt.h1eff
    rdms = nevpt.rdms
    rdm_ca = rdms.ca
    rdm_ccaa = rdms.ccaa
    t1 = nevpt._t1["+1"]
    t1_ = nevpt_grad._t1["+1"].transpose(1,0,3,2)
    koopmans = nevpt._koopmans["+1"]
    overlap = nevpt._overlap["+1"]
    overlap_discard = nevpt._overlap_discard["+1"]
    V1 = nevpt._V1["+1"]
    ic_coeff = nevpt._ic_coeff["+1"]
    s_thres = nevpt.overlap_threshold

    nevpt_grad.v2e.cace[:] -= 2 * einsum('ijxa->jxia', t1)
    nevpt_grad.v2e.cace[:] += 4 * einsum('ijxa->ixja', t1)
    nevpt_grad.v2e.cace[:] += einsum('ijxa,xy->jyia', t1, rdm_ca)
    nevpt_grad.v2e.cace[:] -= 2 * einsum('ijxa,xy->iyja', t1, rdm_ca)
    nevpt_grad.rdms.ca += einsum('ijxa,jyia->xy', t1, v_cace)
    nevpt_grad.rdms.ca -= 2 * einsum('ijxa,iyja->xy', t1, v_cace)

    Delta = e_extern[None, None, :] - e_core[:, None, None] - e_core[None, :, None]
    koopmans_, overlap_, V1_, Delta_ = solve_amplitude(t1_, koopmans, overlap, overlap_discard, V1, Delta, ic_coeff, s_thres)
    nevpt_grad.v2e.cace[:] -= einsum('ijax->jxia', V1_)
    nevpt_grad.v2e.cace[:] += 0.5 * einsum('ijax,xy->jyia', V1_, rdm_ca)
    nevpt_grad.rdms.ca += 0.5 * einsum('ijax,jyia->xy', V1_, v_cace)

    nevpt_grad.h1eff.aa += einsum('xy->xy', koopmans_)
    nevpt_grad.h1eff.aa -= 0.5 * einsum('XY,Xx->Yx', koopmans_, rdm_ca)
    
    nevpt_grad.v2e.aaaa[:] += einsum('XY,xy->XYxy', koopmans_, rdm_ca)
    nevpt_grad.v2e.aaaa[:] -= 0.5 * einsum('XY,yx->XxyY', koopmans_, rdm_ca)
    nevpt_grad.v2e.aaaa[:] -= 0.5 * einsum('XY,Xyxz->Yxyz', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ca -= 0.5 * einsum('XY,Yx->Xx', koopmans_, h1eff.aa)
    nevpt_grad.rdms.ca += einsum('XY,XYxy->xy', koopmans_, v_aaaa)
    nevpt_grad.rdms.ca -= 0.5 * einsum("XY,XxyY->yx", koopmans_, v_aaaa, optimize=True)
    nevpt_grad.rdms.ccaa -= 0.5 * einsum('XY,Yxyz->Xyxz', koopmans_, v_aaaa)

    nevpt_grad.rdms.ca -= 0.5 * overlap_.T

    nevpt_grad.mo_energy.e += Delta_.sum(axis=(0,1))
    nevpt_grad.mo_energy.c -= Delta_.sum(axis=(0,2))
    nevpt_grad.mo_energy.c -= Delta_.sum(axis=(1,2))

    nevpt.log.timer("computing T[+1]^(1) gradients", *cput0)
    return

def compute_t1_m1(nevpt_grad):
    nevpt = nevpt_grad.nevpt
    cput0 = (logger.process_clock(), logger.perf_counter())
    nevpt.log.debug("\nComputing T[-1]^(1) gradients...")

    e_core = nevpt.mo_energy.c
    e_extern = nevpt.mo_energy.e
    h1eff = nevpt.h1eff
    v_ceae = nevpt.v2e.ceae
    v_aaaa = nevpt.v2e.aaaa
    rdms = nevpt.rdms
    rdm_ca = rdms.ca
    rdm_ccaa = rdms.ccaa
    t1 = nevpt._t1["-1"]
    t1_ = nevpt_grad._t1["-1"].transpose(0,2,3,1)
    koopmans = nevpt._koopmans["-1"]
    overlap = nevpt._overlap["-1"]
    overlap_discard = nevpt._overlap_discard["-1"]
    V1 = nevpt._V1["-1"]
    ic_coeff = nevpt._ic_coeff["-1"]
    s_thres = nevpt.overlap_threshold

    nevpt_grad.v2e.ceae[:] += 2 * einsum('ixab,xy->iayb', t1, rdm_ca)
    nevpt_grad.v2e.ceae[:] -= einsum('ixab,xy->ibya', t1, rdm_ca)
    nevpt_grad.rdms.ca += 2 * einsum('ixab,iayb->xy', t1, v_ceae)
    nevpt_grad.rdms.ca -= einsum('ixab,ibya->xy', t1, v_ceae)

    Delta = e_extern[None,None,:] + e_extern[None,:,None] - e_core[:,None,None]
    koopmans_, overlap_, V1_, Delta_ = solve_amplitude(t1_, koopmans, overlap, overlap_discard, V1, Delta, ic_coeff, s_thres)
    V1_ = V1_.transpose(0,3,1,2)
    nevpt_grad.v2e.ceae[:] -= 0.5 * einsum('IXAB,Xx->IAxB', V1_, rdm_ca)
    nevpt_grad.rdms.ca -= 0.5 * einsum('IXAB,IAxB->Xx', V1_, v_ceae)

    nevpt_grad.h1eff.aa += -1/2 * einsum('XY,Xx->Yx', koopmans_, rdm_ca)
    nevpt_grad.v2e.aaaa[:] += -1/2 * einsum('XY,Xyxz->Yxyz', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ca += -1/2 * einsum('XY,Yx->Xx', koopmans_, h1eff.aa)
    nevpt_grad.rdms.ccaa += -1/2 * einsum('XY,Yxyz->Xyxz', koopmans_, v_aaaa)

    nevpt_grad.rdms.ca += 1/2 * einsum('XY->XY', overlap_)

    nevpt_grad.mo_energy.e += Delta_.sum(axis=(0,2))
    nevpt_grad.mo_energy.e += Delta_.sum(axis=(0,1))
    nevpt_grad.mo_energy.c -= Delta_.sum(axis=(1,2))

    nevpt.log.timer("computing T[-1]^(1) gradients", *cput0)
    return

def compute_t1_p2(nevpt_grad):
    nevpt = nevpt_grad.nevpt
    cput0 = (logger.process_clock(), logger.perf_counter())
    nevpt.log.debug("\nComputing T[+2]^(1) gradients...")

    ncore = nevpt.ncore
    ncas = nevpt.ncas
    e_core = nevpt.mo_energy.c
    v_caca = nevpt.v2e.caca
    v_aaaa = nevpt.v2e.aaaa
    h1eff = nevpt.h1eff
    rdms = nevpt.rdms
    rdm_ca = rdms.ca
    rdm_ccaa = rdms.ccaa
    rdm_cccaaa = rdms.cccaaa
    t1 = nevpt._t1["+2"]
    koopmans = nevpt._koopmans["+2"]
    overlap = nevpt._overlap["+2"]
    overlap_discard = nevpt._overlap_discard["+2"]
    V1 = nevpt._V1["+2"]
    ic_coeff = nevpt._ic_coeff["+2"]
    s_thres = nevpt.overlap_threshold

    nevpt_grad.v2e.caca[:] += 2 * einsum('ijxy->ixjy', t1)
    nevpt_grad.v2e.caca[:] += -einsum('ijxy->jxiy', t1)
    nevpt_grad.v2e.caca[:] += 1/2 * einsum('ijxy,xyzw->izjw', t1, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/2 * einsum('ijxy,izjw->xyzw', t1, v_caca)
    nevpt_grad.v2e.caca[:] += einsum('ijxy,xz->iyjz', t1, rdm_ca)
    nevpt_grad.rdms.ca += einsum('ijxy,iyjz->xz', t1, v_caca)
    nevpt_grad.v2e.caca[:] += -2 * einsum('ijxy,yz->ixjz', t1, rdm_ca)
    nevpt_grad.rdms.ca += -2 * einsum('ijxy,ixjz->yz', t1, v_caca)

    Delta = -e_core[:,None] - e_core[None,:]
    t1_ = nevpt_grad._t1["+2"].reshape(ncore,ncore,ncas*ncas)
    koopmans_, overlap_, V1_, Delta_ = solve_amplitude(t1_, koopmans, overlap, overlap_discard, V1, Delta, ic_coeff, s_thres)
    koopmans_ = koopmans_.reshape([ncas]*4)
    overlap_ = overlap_.reshape([ncas]*4)
    V1_ = V1_.reshape(ncore,ncore,ncas,ncas)

    nevpt_grad.v2e.caca[:] += -einsum('IJXY->IXJY', V1_)
    nevpt_grad.v2e.caca[:] += 1/2 * einsum('IJXY,Yx->IXJx', V1_, rdm_ca)
    nevpt_grad.rdms.ca += 1/2 * einsum('IJXY,IXJx->Yx', V1_, v_caca)
    nevpt_grad.v2e.caca[:] += 1/2 * einsum('IJXY,Xx->IxJY', V1_, rdm_ca)
    nevpt_grad.rdms.ca += 1/2 * einsum('IJXY,IxJY->Xx', V1_, v_caca)
    nevpt_grad.v2e.caca[:] += -1/3 * einsum('IJXY,XYxy->IxJy', V1_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += -1/3 * einsum('IJXY,IxJy->XYxy', V1_, v_caca)
    nevpt_grad.v2e.caca[:] += -1/6 * einsum('IJXY,XYyx->IxJy', V1_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += -1/6 * einsum('IJXY,IxJy->XYyx', V1_, v_caca)

    nevpt_grad.v2e.aaaa[:] += einsum('XYWZ->WXZY', koopmans_)
    nevpt_grad.h1eff.aa += einsum('XYWZ,YZ->WX', koopmans_, np.eye(ncas))
    nevpt_grad.h1eff.aa += einsum('XYWZ,WX->YZ', koopmans_, np.eye(ncas))
    nevpt_grad.h1eff.aa += -1/2 * einsum('XYWZ,YZ->WX', koopmans_, rdm_ca)
    nevpt_grad.rdms.ca += -1/2 * einsum('XYWZ,WX->YZ', koopmans_, h1eff.aa)
    nevpt_grad.h1eff.aa += 1/6 * einsum('XYWZ,XYZx->Wx', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/6 * einsum('XYWZ,Wx->XYZx', koopmans_, h1eff.aa)
    nevpt_grad.h1eff.aa += 1/3 * einsum('XYWZ,XYxZ->Wx', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/3 * einsum('XYWZ,Wx->XYxZ', koopmans_, h1eff.aa)
    nevpt_grad.h1eff.aa += -1/2 * einsum('XYWZ,WX->YZ', koopmans_, rdm_ca)
    nevpt_grad.rdms.ca += -1/2 * einsum('XYWZ,YZ->WX', koopmans_, h1eff.aa)
    nevpt_grad.h1eff.aa += 1/3 * einsum('XYWZ,WxXY->Zx', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/3 * einsum('XYWZ,Zx->WxXY', koopmans_, h1eff.aa)
    nevpt_grad.h1eff.aa += 1/6 * einsum('XYWZ,WxYX->Zx', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/6 * einsum('XYWZ,Zx->WxYX', koopmans_, h1eff.aa)
    nevpt_grad.v2e.aaaa[:] += -1/2 * einsum('XYWZ,Yx->WXZx', koopmans_, rdm_ca)
    nevpt_grad.rdms.ca += -1/2 * einsum('XYWZ,WXZx->Yx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/2 * einsum('XYWZ,Zx->WXxY', koopmans_, rdm_ca)
    nevpt_grad.rdms.ca += -1/2 * einsum('XYWZ,WXxY->Zx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/2 * einsum('XYWZ,YxZy->WXxy', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += -1/2 * einsum('XYWZ,WXxy->YxZy', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/2 * einsum('XYWZ,Xx->WxZY', koopmans_, rdm_ca)
    nevpt_grad.rdms.ca += -1/2 * einsum('XYWZ,WxZY->Xx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/3 * einsum('XYWZ,XYxy->WxZy', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/3 * einsum('XYWZ,WxZy->XYxy', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/6 * einsum('XYWZ,XYyx->WxZy', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/6 * einsum('XYWZ,WxZy->XYyx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/3 * einsum('XYWZ,YyZx->WxyX', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/3 * einsum('XYWZ,WxyX->YyZx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/6 * einsum('XYWZ,YyxZ->WxyX', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/6 * einsum('XYWZ,WxyX->YyxZ', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/6 * einsum('XYWZ,XyZx->WxyY', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/6 * einsum('XYWZ,WxyY->XyZx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/3 * einsum('XYWZ,XyxZ->WxyY', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/3 * einsum('XYWZ,WxyY->XyxZ', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/6 * einsum('XYWZ,XYyZzx->Wxyz', koopmans_, rdm_cccaaa)
    nevpt_grad.rdms.cccaaa += -1/6 * einsum('XYWZ,Wxyz->XYyZzx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/6 * einsum('XYWZ,XYyxZz->Wxyz', koopmans_, rdm_cccaaa)
    nevpt_grad.rdms.cccaaa += 1/6 * einsum('XYWZ,Wxyz->XYyxZz', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/6 * einsum('XYWZ,XYyxzZ->Wxyz', koopmans_, rdm_cccaaa)
    nevpt_grad.rdms.cccaaa += -1/6 * einsum('XYWZ,Wxyz->XYyxzZ', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/6 * einsum('XYWZ,XYyzZx->Wxyz', koopmans_, rdm_cccaaa)
    nevpt_grad.rdms.cccaaa += -1/6 * einsum('XYWZ,Wxyz->XYyzZx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/6 * einsum('XYWZ,XYyzxZ->Wxyz', koopmans_, rdm_cccaaa)
    nevpt_grad.rdms.cccaaa += -1/6 * einsum('XYWZ,Wxyz->XYyzxZ', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/2 * einsum('XYWZ,Wx->XxYZ', koopmans_, rdm_ca)
    nevpt_grad.rdms.ca += -1/2 * einsum('XYWZ,XxYZ->Wx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/6 * einsum('XYWZ,WyYx->XxyZ', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/6 * einsum('XYWZ,XxyZ->WyYx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/3 * einsum('XYWZ,WyxY->XxyZ', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/3 * einsum('XYWZ,XxyZ->WyxY', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += -1/2 * einsum('XYWZ,WxXy->YZxy', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += -1/2 * einsum('XYWZ,YZxy->WxXy', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/3 * einsum('XYWZ,WyXx->YxyZ', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/3 * einsum('XYWZ,YxyZ->WyXx', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/6 * einsum('XYWZ,WyxX->YxyZ', koopmans_, rdm_ccaa)
    nevpt_grad.rdms.ccaa += 1/6 * einsum('XYWZ,YxyZ->WyxX', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/3 * einsum('XYWZ,WxzXYy->Zxyz', koopmans_, rdm_cccaaa)
    nevpt_grad.rdms.cccaaa += 1/3 * einsum('XYWZ,Zxyz->WxzXYy', koopmans_, v_aaaa)
    nevpt_grad.v2e.aaaa[:] += 1/6 * einsum('XYWZ,WxzYXy->Zxyz', koopmans_, rdm_cccaaa)
    nevpt_grad.rdms.cccaaa += 1/6 * einsum('XYWZ,Zxyz->WxzYXy', koopmans_, v_aaaa)
    nevpt_grad.h1eff.aa += -1/2 * einsum('XYWZ,YZ,Xx->Wx', koopmans_, np.eye(ncas), rdm_ca)
    nevpt_grad.rdms.ca += -1/2 * einsum('XYWZ,Wx,YZ->Xx', koopmans_, h1eff.aa, np.eye(ncas))
    nevpt_grad.h1eff.aa += -1/2 * einsum('XYWZ,WX,Yx->Zx', koopmans_, np.eye(ncas), rdm_ca)
    nevpt_grad.rdms.ca += -1/2 * einsum('XYWZ,Zx,WX->Yx', koopmans_, h1eff.aa, np.eye(ncas))
    nevpt_grad.v2e.aaaa[:] += einsum('XYWZ,WX,xy->YZxy', koopmans_, np.eye(ncas), rdm_ca)
    nevpt_grad.rdms.ca += einsum('XYWZ,WX,YZxy->xy', koopmans_, np.eye(ncas), v_aaaa)
