    nevpt_grad.h1eff.ce += 2 * einsum('ixay,yx->ia', t1_caea, rdm_ca)
    nevpt_grad.rdms.ca += 2 * einsum('ia,ixay->yx', h1eff.ce, t1_caea)
    nevpt_grad.h1eff.ce += -einsum('ixya,yx->ia', t1_caae, rdm_ca)
    nevpt_grad.rdms.ca += -einsum('ia,ixya->yx', h1eff.ce, t1_caae)
